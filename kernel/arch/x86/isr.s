.section .text
.extern interrupt_handler
isr_wrapper:
    # store all registers
    pusha
    # store data segment
    xor %eax, %eax
    mov %ds, %ax
    push %eax
    # store page directory
    mov %cr3, %eax
    push %eax
    # load kernel data segment
    mov $0x10, %ax
    mov %ax, %ds
    mov %ax, %es
    # interrupt_frame_t*
    push %esp
    call interrupt_handler
    add $4, %esp
    # load page directory
    pop %eax
    test %eax, %eax
    jz 1f
    mov %eax, %cr3
1:  # restore data segment
    pop %eax
    mov %ax, %ds
    mov %ax, %es
    # restore registers
    popa
    # clear error_code and N
    add $8, %esp
    iret


.macro isr_error N
isr\N:
    push $\N
    jmp isr_wrapper
.endm

.macro isr_no_error N
isr\N:
    push $0
